// ============================================================================
// SCADA Tag Database & PLC I/O Image Table
// Educational representation of industrial tag mapping (IEC 61131-3)
// Notice: Simulator state presentation only, labeled as SIMULATED.
// ============================================================================

import { ScadaTag, MachineState, MotorTelemetry, SensorStatus, DiverterStatus, ProductionCounters, ActiveFaults, SimSettings } from '../types/scada';

export class TagDatabase {
  public static generateTags(
    machineState: MachineState,
    motor: MotorTelemetry,
    sensor: SensorStatus,
    diverter: DiverterStatus,
    counters: ProductionCounters,
    faults: ActiveFaults,
    settings?: SimSettings
  ): ScadaTag[] {
    const now = Date.now();

    return [
      {
        name: 'CONV_STATE_ENUM',
        address: '%MW100',
        type: 'STRING',
        direction: 'INTERNAL',
        value: machineState,
        description: 'Global state machine status word (IDLE/RUNNING/FAULT/ESTOP)',
        lastUpdated: now,
      },
      {
        name: 'CONV_MOTOR_RUN',
        address: '%QX0.0',
        type: 'BOOL',
        direction: 'OUTPUT',
        value: motor.runCommand,
        description: 'Main conveyor motor contactor command coil',
        lastUpdated: now,
      },
      {
        name: 'CONV_SPEED_SP',
        address: '%MD102',
        type: 'REAL',
        direction: 'OUTPUT',
        value: motor.targetSpeedMs,
        unit: 'm/s',
        description: 'VFD Speed setpoint commanded from SCADA operator station',
        lastUpdated: now,
      },
      {
        name: 'CONV_SPEED_PV',
        address: '%MD106',
        type: 'REAL',
        direction: 'INPUT',
        value: motor.actualSpeedMs,
        unit: 'm/s',
        description: 'VFD Tachometer process variable feedback speed',
        lastUpdated: now,
      },
      {
        name: 'CONV_VFD_FREQ',
        address: '%MD110',
        type: 'REAL',
        direction: 'INPUT',
        value: motor.frequencyHz,
        unit: 'Hz',
        description: 'Inverter output electrical frequency',
        lastUpdated: now,
      },
      {
        name: 'CONV_MOTOR_RPM',
        address: '%MW114',
        type: 'INT',
        direction: 'INPUT',
        value: motor.rpm,
        unit: 'RPM',
        description: '4-pole motor rotor angular velocity',
        lastUpdated: now,
      },
      {
        name: 'MOTOR_TEMP_PV',
        address: '%MD116',
        type: 'REAL',
        direction: 'INPUT',
        value: motor.temperatureC,
        unit: '°C',
        description: 'Stator winding PT100 resistance temperature detector',
        lastUpdated: now,
      },
      {
        name: 'MOTOR_LOAD_PCT',
        address: '%MD120',
        type: 'REAL',
        direction: 'INPUT',
        value: motor.loadPercent,
        unit: '%',
        description: 'Motor electrical shaft torque load percentage',
        lastUpdated: now,
      },
      {
        name: 'MOTOR_CURRENT_A',
        address: '%MD124',
        type: 'REAL',
        direction: 'INPUT',
        value: motor.currentAmps,
        unit: 'A',
        description: 'Motor phase RMS current draw (FLA 12.5A)',
        lastUpdated: now,
      },
      {
        name: 'SENSOR_01_DETECT',
        address: '%IX0.1',
        type: 'BOOL',
        direction: 'INPUT',
        value: sensor.active,
        description: 'Photoelectric retroreflective infeed inspection beam',
        lastUpdated: now,
      },
      {
        name: 'SENSOR_01_TOTAL',
        address: '%MD130',
        type: 'INT',
        direction: 'INTERNAL',
        value: sensor.detectionCount,
        unit: 'units',
        description: 'Total cumulative bottle presence count at station 1',
        lastUpdated: now,
      },
      {
        name: 'DIVERTER_01_CMD',
        address: '%QX0.1',
        type: 'BOOL',
        direction: 'OUTPUT',
        value: diverter.actuated,
        description: 'Pneumatic 5/2 directional solenoid valve coil (Chute B)',
        lastUpdated: now,
      },
      {
        name: 'DIVERTER_STROKES',
        address: '%MD134',
        type: 'INT',
        direction: 'INTERNAL',
        value: diverter.strokeCount,
        unit: 'cycles',
        description: 'Total mechanical stroke count for preventive maintenance',
        lastUpdated: now,
      },
      {
        name: 'ESTOP_ACTIVE',
        address: '%IX0.0',
        type: 'BOOL',
        direction: 'INPUT',
        value: faults.emergencyStop || machineState === 'EMERGENCY_STOP',
        description: 'Mushroom Emergency Stop safety circuit loop (NC contact)',
        lastUpdated: now,
      },
      {
        name: 'JAM_SENSOR_TRIP',
        address: '%IX0.6',
        type: 'BOOL',
        direction: 'INPUT',
        value: faults.jam,
        description: 'Optical beam continuous block accumulation flag (>3s)',
        lastUpdated: now,
      },
      {
        name: 'COUNT_CAT_A',
        address: '%MW140',
        type: 'INT',
        direction: 'INTERNAL',
        value: counters.categoryA,
        unit: 'units',
        description: 'Category A (Straight-through 500ml) production counter',
        lastUpdated: now,
      },
      {
        name: 'COUNT_CAT_B',
        address: '%MW142',
        type: 'INT',
        direction: 'INTERNAL',
        value: counters.categoryB,
        unit: 'units',
        description: 'Category B (Diverted 1000ml) production counter',
        lastUpdated: now,
      },
      {
        name: 'THROUGHPUT_BPM',
        address: '%MW144',
        type: 'INT',
        direction: 'INTERNAL',
        value: counters.currentBpm,
        unit: 'BPM',
        description: 'Instantaneous line rate (Bottles Per Minute)',
        lastUpdated: now,
      },
      {
        name: 'UTILIZATION_PCT',
        address: '%MD146',
        type: 'REAL',
        direction: 'INTERNAL',
        value: counters.utilizationPercent,
        unit: '%',
        description: 'Machine Overall Utilization efficiency percentage',
        lastUpdated: now,
      },
      {
        name: 'REJECT_COUNT',
        address: '%MW148',
        type: 'INT',
        direction: 'INTERNAL',
        value: counters.rejectedCount,
        unit: 'units',
        description: 'Defective bottle quality reject accumulator',
        lastUpdated: now,
      },
      {
        name: 'BATCH_TARGET',
        address: '%MW150',
        type: 'INT',
        direction: 'INTERNAL',
        value: settings?.batchTarget ?? 0,
        unit: 'units',
        description: 'Batch production quantity setpoint (0 = continuous run)',
        lastUpdated: now,
      },
      {
        name: 'BATCH_PROGRESS',
        address: '%MD152',
        type: 'REAL',
        direction: 'INTERNAL',
        value: settings && settings.batchTarget > 0 
          ? Math.min(100, Math.round(((counters.categoryA + counters.categoryB) / settings.batchTarget) * 100))
          : 0,
        unit: '%',
        description: 'Real-time batch fulfillment progress percentage',
        lastUpdated: now,
      },
    ];
  }
}
